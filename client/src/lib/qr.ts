// The counter QR code on the Settings page. Loaded on first use (dynamic import), like lib/excel.ts.
import QRCode from 'qrcode';
import { downloadBlob } from './download';

const options = { margin: 2, errorCorrectionLevel: 'M' } as const;

/** The QR code as SVG markup (needs no canvas, so it also renders in tests). */
export const qrSvg = (text: string) => QRCode.toString(text, { ...options, type: 'svg' });

/** Downloads the QR code as a large PNG, for printing elsewhere. */
export async function downloadQrPng(text: string, fileName: string) {
  const dataUrl = await QRCode.toDataURL(text, { ...options, width: 1024 });
  downloadBlob(await (await fetch(dataUrl)).blob(), fileName);
}

/** Opens a print window with the title and the QR code. */
export function printQr(svg: string, title: string) {
  const w = window.open('', '_blank');
  if (!w) return;
  const doc = w.document;
  doc.title = title;
  doc.body.style.cssText = 'margin:0;font-family:sans-serif;text-align:center;padding-top:2cm';
  const h = doc.createElement('h1');
  h.textContent = title;
  const box = doc.createElement('div');
  box.style.cssText = 'width:12cm;margin:1cm auto';
  box.innerHTML = svg; // generated by the qrcode library
  doc.body.append(h, box);
  w.focus();
  w.print();
}
